export type KanaWord = {
  kana: string;
  meaning: string;
  level: number;
};

/**
 * Words available for a given (jlpt level, kana length) combo, deduplicated by
 * reading. `level` is exclusive-min: 5 matches N5 only, 1 matches N1 only.
 */
export const WORDS_BY_LEVEL_LENGTH: Record<string, KanaWord> = {};

for (const [level, kana, meaning] of JLPT_WORDS) {
  const key = `${level}:${kana.length}:${kana}`;
  if (!(key in WORDS_BY_LEVEL_LENGTH)) {
    WORDS_BY_LEVEL_LENGTH[key] = { kana, meaning, level };
  }
}

export const WORD_LENGTHS = [2, 3, 4, 5, 6] as const;

export const JLPT_LEVELS = [
  { value: 5, label: "N5", name: "N5 · Beginner" },
  { value: 4, label: "N4", name: "N4 · Lower Intermediate" },
  { value: 3, label: "N3", name: "N3 · Intermediate" },
  { value: 2, label: "N2", name: "N2 · Upper Intermediate" },
  { value: 1, label: "N1", name: "N1 · Advanced" },
] as const;

const POOL_CACHE: Record<string, KanaWord[]> = {};

/** Cache of words with a given level and kana length. */
export function wordsFor(level: number, length: number): KanaWord[] {
  const key = `${level}:${length}`;
  if (POOL_CACHE[key]) return POOL_CACHE[key];
  const list = Object.values(WORDS_BY_LEVEL_LENGTH).filter(
    (w) => w.level === level && w.kana.length === length
  );
  POOL_CACHE[key] = list;
  return list;
}

/** Pick a random word for a combo, or null if the pool is empty. */
export function randomWordFor(level: number, length: number): KanaWord | null {
  const pool = wordsFor(level, length);
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}
